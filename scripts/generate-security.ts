import { writeFileSync } from "node:fs";
import { snapshotSchema, mediaSchema } from "../src/publicValidation";
// Run npm run security:schema after changing the public DTO; commit the generated SQL.
writeFileSync(
  "supabase/security-schema.sql",
  `-- Generated by scripts/generate-security.ts. No credentials.
create or replace function public.scout_payload_schema(kind text) returns jsonb
language sql immutable set search_path = '' as $schema$
select case kind when 'snapshot' then '${JSON.stringify(snapshotSchema).replaceAll("'", "''")}'::jsonb
when 'media' then '${JSON.stringify(mediaSchema).replaceAll("'", "''")}'::jsonb else null end;
$schema$;
revoke all on function public.scout_payload_schema(text) from public, anon, authenticated;
`,
);
